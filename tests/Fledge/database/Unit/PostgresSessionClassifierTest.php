<?php

use Fledge\Async\Database\Postgres\Internal\PostgresSessionClassifier;

it('classifies only statements that cannot change the Postgres session as clean', function (string $sql, bool $clean) {
    expect(PostgresSessionClassifier::leavesSessionUnchanged($sql))->toBe($clean);
})->with([
    // Clean: plain reads that leave nothing behind in the session.
    ['select * from "users" where "id" = $1 limit 1', true],
    ['select count(*) as aggregate from "users"', true],
    ['SELECT 1', true],
    ['SELECT 1;', true],
    ['  (select "a" from "t") union all (select "b" from "u")', true],
    ['select * from "users" where "email" = \'a;b -- c /* d */\'', true],
    ['select * from "t" where "name" = E\'it\\\'s\'', true],
    ['select $$; SET x = 1 $$ as v', true],
    ['select $tag$ quoted ; DO $tag$ as v', true],
    ['select length($q$ nextval(\'s\') $q$) as v', true],
    ['select 1,$q$ nextval(\'s\') $q$ as v', true],
    ['select "a",$$ x $$ from "t"', true],
    ['select "a"::numeric(10, 2), "b"::varchar(255) from "t"', true],
    ['select * from "posts" where "data"->>\'k\' = $1 and "tags" @> $2::jsonb', true],
    ['select exists(select 1 from "t" where "id" = $1) as "exists"', true],
    ['select coalesce(max("id"), 0) from "t" for update', true],
    ['select * from "t" where "id" = $1 for no key update skip locked', true],
    ['select lower("name"), upper("name"), now(), random() from "t" order by random()', true],
    ['select to_tsvector(\'english\', "body") @@ plainto_tsquery(\'english\', $1) from "t"', true],
    ['with recursive "c" as (select 1 as n union all select n + 1 from "c" where n < 3) select * from "c"', true],
    ['SHOW TimeZone', true],
    ['SHOW standard_conforming_strings', true],
    ['EXPLAIN SELECT * FROM "t"', true],
    ['VALUES (1), (2)', true],
    ['TABLE "users"', true],
    ['SET LOCAL statement_timeout = \'5s\'', true],
    ['set local search_path = pg_catalog', true],
    ['SET TRANSACTION ISOLATION LEVEL SERIALIZABLE', true],
    ['SET CONSTRAINTS ALL DEFERRED', true],
    ['SAVEPOINT "sp1"', true],
    ['RELEASE SAVEPOINT "sp1"', true],
    ['ROLLBACK TO SAVEPOINT "sp1"', true],
    ['select pg_advisory_xact_lock(1)', true],
    ['select pg_try_advisory_xact_lock($1)', true],
    ['DECLARE c CURSOR FOR SELECT * FROM "t"', true],
    ['FETCH 10 FROM c', true],
    ['CLOSE c', true],
    ['NOTIFY "chan", \'payload\'', true],
    ['select version()', true],
    ['select current_setting(\'TimeZone\')', true],
    ['select pg_backend_pid()', true],

    // Dirty: session settings.
    ['SET statement_timeout = 0', false],
    ['SET SESSION statement_timeout = 0', false],
    ['set search_path to "public"', false],
    ['SET ROLE "admin"', false],
    ['SET SESSION AUTHORIZATION "admin"', false],
    ['SET TIME ZONE \'UTC\'', false],
    ['SET SESSION CHARACTERISTICS AS TRANSACTION ISOLATION LEVEL SERIALIZABLE', false],
    ['RESET ALL', false],
    ['select set_config(\'TimeZone\', \'UTC\', false)', false],
    ['select set_config(\'TimeZone\', \'UTC\', true)', false],

    // Dirty: advisory locks held by the session.
    ['select pg_advisory_lock(1)', false],
    ['select pg_try_advisory_lock(1)', false],
    ['select pg_advisory_lock_shared(1)', false],
    ['select pg_advisory_unlock(1)', false],
    ['select pg_advisory_unlock_all()', false],

    // Dirty: sequences (currval / lastval read what nextval left in the session).
    ['insert into "users" ("name") values ($1)', false],
    ['insert into "users" ("name") values ($1) returning "id"', false],
    ['select nextval(\'users_id_seq\')', false],
    ['select setval(\'users_id_seq\', 1)', false],
    ['select currval(\'users_id_seq\')', false],
    ['select lastval()', false],
    ['update "users" set "id" = default where "id" = 1', false],
    ['with "x" as (insert into "t" default values returning *) select * from "x"', false],
    ['MERGE INTO "t" USING "s" ON "t"."id" = "s"."id" WHEN NOT MATCHED THEN INSERT VALUES ("s"."id")', false],

    // Dirty: DML, because a trigger on the table can do anything a function can.
    ['update "users" set "name" = $1 where "id" = $2', false],
    ['delete from "users" where "id" = $1', false],
    ['UPDATE users SET name = \'x\'', false],
    ['with "d" as (delete from "t" returning *) select * from "d"', false],
    ['with "u" as (update "t" set "a" = 1 returning *) select count(*) from "u"', false],
    ['EXPLAIN ANALYZE UPDATE "t" SET "a" = 1', false],

    // Dirty: temp tables, SELECT INTO, prepared statements, held cursors, LISTEN.
    ['CREATE TEMP TABLE "t" ("id" int)', false],
    ['CREATE TEMPORARY TABLE "t" AS SELECT 1', false],
    ['select 1 as a into temp "t"', false],
    ['select * into "t2" from "t"', false],
    ['PREPARE "p" AS SELECT 1', false],
    ['EXECUTE "p"', false],
    ['DEALLOCATE ALL', false],
    ['DECLARE c CURSOR WITH HOLD FOR SELECT 1', false],
    ['LISTEN "chan"', false],
    ['UNLISTEN *', false],

    // Dirty: code the tracker cannot see into, and anything else.
    ['DO $$ BEGIN PERFORM set_config(\'x.y\', \'1\', false); END $$', false],
    ['select "my_function"()', false],
    ['select my_function($1)', false],
    ['select "public"."my_function"()', false],
    ['select pg_catalog.set_config(\'a.b\', \'1\', false)', false],
    ['select * from my_set_returning_function()', false],
    // A non-ASCII letter continues a name, so these are user functions, not count() or lower().
    ['select ñcount(*) from t', false],
    ['select xñcount(1) from t', false],
    ['select ålower("name") from t', false],
    ['select s.ñcount(1) from s', false],
    ['select ñ(1)', false],
    ['CALL my_procedure()', false],
    ['COPY "t" FROM STDIN', false],
    ['EXPLAIN ANALYZE INSERT INTO "t" VALUES (1)', false],
    ['EXPLAIN (ANALYZE) SELECT nextval(\'s\')', false],
    ['BEGIN', false],
    ['START TRANSACTION', false],
    ['COMMIT', false],
    ['ROLLBACK', false],
    ['LOCK TABLE "t"', false],
    ['CREATE TABLE "t" ("id" int)', false],
    ['DROP TABLE "t"', false],
    ['TRUNCATE "t"', false],
    ['VACUUM', false],
    ['DISCARD ALL', false],
    ['LOAD \'auto_explain\'', false],

    // Dirty: anything that could hide a second statement or that the scanner cannot read.
    ['select 1; set statement_timeout = 0', false],
    ['select 1; select 2', false],
    ['select 1 -- comment', false],
    ['select /* comment */ 1', false],
    ['select \'unterminated', false],
    ['select "unterminated', false],
    ['select $$unterminated', false],
    // $ continues an identifier, so a$x$ is a name, not a dollar-quote opener.
    ['SELECT a$x$, nextval(\'s\'), b$x$ FROM t', false],
    ['select a$$, setval(\'s\', 1), b$$ from t', false],
    ['select 1$q$, nextval(\'s\'), 2$q$', false],
    ['select \'a\\\'; set statement_timeout = 0; --\'', false],
    ['select date\'\\\'; set statement_timeout = 0; --\'', false],
    ['', false],
]);
